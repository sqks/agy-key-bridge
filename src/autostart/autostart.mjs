/**
 * 开机自启。按平台分三条路：
 *
 * - Windows：注册表 HKCU\...\Run 指向 wscript → pythonw → launcher.py。
 *   绕这一圈是为了不弹控制台窗口（pythonw 是 GUI 子系统解释器）；注册表里的
 *   启动项如果直接写 node.exe，登录时会挂一个黑框在那儿。
 * - Linux：写 ~/.config/systemd/user/agy-bridge.service 再 enable --now。
 *   没有 systemd（容器 / WSL）时只落文件并明确告知，不假装成功。
 * - 其它平台：返回不支持，交给调用方自己的 supervisor。
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { ROOT } from '../state/state.mjs';

const RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run';
const VALUE_NAME = 'AgyKeyBridge';
const LAUNCHER = path.join(ROOT, 'script', 'launcher.py');
const LEGACY_LAUNCHER = path.join(ROOT, 'start-hidden.vbs');
const LEGACY_LAUNCHER_ROOT = path.join(ROOT, 'launcher.py');

const UNIT_NAME = 'agy-bridge.service';
const UNIT_DIR = path.join(os.homedir(), '.config', 'systemd', 'user');
const UNIT_PATH = path.join(UNIT_DIR, UNIT_NAME);

const isWindows = process.platform === 'win32';
const isLinux = process.platform === 'linux';
const isMac = process.platform === 'darwin';

function run(exe, args) {
  return spawnSync(exe, args, { windowsHide: true, encoding: 'utf8' });
}

function firstExisting(candidates) {
  for (const candidate of candidates) {
    try {
      if (candidate && fs.existsSync(candidate)) return candidate;
    } catch {}
  }
  return null;
}

function scanPythonw() {
  const found = [];
  const roots = [
    path.join(process.env.LOCALAPPDATA || '', 'Programs', 'Python'),
    process.env.PROGRAMFILES || 'C:\\Program Files',
    'C:',
  ];
  for (const root of roots) {
    let entries = [];
    try {
      entries = fs.readdirSync(root, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (!entry.isDirectory() || !/^Python3\d+$/i.test(entry.name)) continue;
      const exe = path.join(root, entry.name, 'pythonw.exe');
      if (fs.existsSync(exe)) found.push(exe);
    }
  }
  found.sort((a, b) => {
    const num = (p) => Number((p.match(/Python3(\d+)/i) || [])[1] || 0);
    return num(b) - num(a);
  });
  return found;
}

/** Windows 上找 pythonw.exe：GUI 子系统解释器，启动时不分配控制台。 */
export function pythonwPath() {
  if (!isWindows) return null;
  const explicit = process.env.PYTHONW_PATH;
  if (explicit && fs.existsSync(explicit)) return explicit;

  const scanned = firstExisting(scanPythonw());
  if (scanned) return scanned;

  const onPath = run('where.exe', ['pythonw.exe']);
  if (onPath.status === 0) {
    const first = String(onPath.stdout || '').split(/\r?\n/).map((s) => s.trim()).filter(Boolean)[0];
    if (first && fs.existsSync(first)) return first;
  }
  return null;
}

function pythonExeFor(pythonw) {
  const sibling = path.join(path.dirname(pythonw), 'python.exe');
  return fs.existsSync(sibling) ? sibling : pythonw;
}

function launcherSource(pythonw) {
  const py = (value) => `r"${value}"`;
  return `# AGY Key Bridge launcher - starts the Node service detached, no console window.
# Generated by src/autostart/autostart.mjs; delete the Run entry to disable autostart.
import json
import os
import socket
import shutil
import subprocess
import sys
from pathlib import Path

# 不写死任何绝对路径：项目根从本文件位置推（script/ 的上一级），
# node 按 环境变量 → data/env.json 缓存 → PATH → 常见安装目录 依次找。
# 所以整个目录可以原样搬到别的路径或别的机器。
ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT / "src" / "server" / "server.mjs"
STATE = ROOT / "data" / "state.json"
ENV_CACHE = ROOT / "data" / "env.json"
LOG = ROOT / "data" / "launcher.log"
DEFAULT_PORT = 47913


def node_executable():
    explicit = os.environ.get("AGY_NODE")
    if explicit and Path(explicit).is_file():
        return Path(explicit)

    try:
        home = json.loads(ENV_CACHE.read_text(encoding="utf-8")).get("nodeHome")
    except Exception:
        home = None
    if home:
        for candidate in (Path(home) / "node.exe", Path(home) / "bin" / "node"):
            if candidate.is_file():
                return candidate

    found = shutil.which("node")
    if found:
        return Path(found)

    guesses = [
        Path(os.environ.get("ProgramFiles", "C:/Program Files")) / "nodejs" / "node.exe",
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "nodejs" / "node.exe",
        Path("/usr/local/bin/node"),
        Path("/usr/bin/node"),
    ]
    for candidate in guesses:
        if candidate.is_file():
            return candidate
    return None

CREATE_NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)


def service_port():
    try:
        with open(STATE, "r", encoding="utf-8") as fh:
            return int(json.load(fh).get("port") or DEFAULT_PORT)
    except Exception:
        return DEFAULT_PORT


def already_running(port):
    probe = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    probe.settimeout(0.4)
    try:
        return probe.connect_ex(("127.0.0.1", port)) == 0
    finally:
        probe.close()


def main():
    node = node_executable()
    if node is None:
        return 1
    if not SERVER.is_file():
        return 1
    if already_running(service_port()):
        return 0
    log = subprocess.DEVNULL
    try:
        os.makedirs(os.path.dirname(LOG), exist_ok=True)
        log = open(LOG, "a", encoding="utf-8")
    except Exception:
        pass
    subprocess.Popen(
        [str(node), str(SERVER), "--autostart"],
        cwd=str(ROOT),
        stdin=subprocess.DEVNULL,
        stdout=log,
        stderr=log,
        creationflags=CREATE_NO_WINDOW,
        close_fds=False,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
`;
}

function writeLauncher(pythonw) {
  fs.mkdirSync(path.dirname(LAUNCHER), { recursive: true });
  fs.writeFileSync(LAUNCHER, launcherSource(pythonw), 'utf8');
  const check = run(pythonExeFor(pythonw), ['-m', 'py_compile', LAUNCHER]);
  if (check.status !== 0) {
    throw new Error(`launcher.py failed to compile: ${(check.stderr || check.stdout || '').trim()}`);
  }
  return LAUNCHER;
}

function removeLegacyLauncher() {
  // 早先版本把 launcher.py / start-hidden.vbs 放在项目根，迁到 script/ 后清掉残留
  for (const legacy of [LEGACY_LAUNCHER, LEGACY_LAUNCHER_ROOT]) {
    try {
      if (fs.existsSync(legacy)) fs.unlinkSync(legacy);
    } catch {}
  }
}

// ---------------------------------------------------------------- linux

function systemdAvailable() {
  const probe = run('systemctl', ['--user', 'show-environment']);
  return probe.status === 0;
}

function writeUnit() {
  fs.mkdirSync(UNIT_DIR, { recursive: true });
  const unit = `[Unit]
Description=AGY Key Bridge (Antigravity relay)
After=network-online.target

[Service]
Type=simple
WorkingDirectory=${ROOT}
ExecStart=${process.execPath} ${path.join(ROOT, 'src', 'server', 'server.mjs')} --autostart
Restart=always
RestartSec=3
Environment=NODE_ENV=production

[Install]
WantedBy=default.target
`;
  fs.writeFileSync(UNIT_PATH, unit, 'utf8');
  return UNIT_PATH;
}

function linuxInstalled() {
  if (!fs.existsSync(UNIT_PATH)) return false;
  if (!systemdAvailable()) return true;
  const r = run('systemctl', ['--user', 'is-enabled', UNIT_NAME]);
  return r.status === 0 || String(r.stdout).trim() === 'enabled';
}

function linuxSet(enabled) {
  if (enabled) {
    writeUnit();
    if (!systemdAvailable()) {
      return {
        ok: true,
        enabled: true,
        command: UNIT_PATH,
        note: 'systemd 不可用，只写了 unit 文件；请手动 daemon-reload / enable',
      };
    }
    run('systemctl', ['--user', 'daemon-reload']);
    const r = run('systemctl', ['--user', 'enable', '--now', UNIT_NAME]);
    if (r.status !== 0) {
      return { ok: false, error: (r.stderr || r.stdout || 'systemctl enable failed').trim() };
    }
    return { ok: true, enabled: true, command: `systemctl --user status ${UNIT_NAME}` };
  }

  if (systemdAvailable()) {
    run('systemctl', ['--user', 'disable', '--now', UNIT_NAME]);
    run('systemctl', ['--user', 'daemon-reload']);
  }
  try {
    if (fs.existsSync(UNIT_PATH)) fs.unlinkSync(UNIT_PATH);
  } catch {}
  return { ok: true, enabled: false };
}

// ---------------------------------------------------------------- api

let installedCache = { value: false, at: 0 };

export function autostartInstalled(force = false) {
  if (!isWindows && !isLinux) return false;
  if (!force && Date.now() - installedCache.at < 30_000) return installedCache.value;
  const value = isWindows
    ? (() => {
        const r = run('reg.exe', ['query', RUN_KEY, '/v', VALUE_NAME]);
        return r.status === 0 && String(r.stdout || '').includes(VALUE_NAME);
      })()
    : linuxInstalled();
  installedCache = { value, at: Date.now() };
  return value;
}

export function setAutostart(enabled) {
  if (isLinux) {
    const result = linuxSet(enabled);
    installedCache = { value: Boolean(result.ok && enabled), at: Date.now() };
    return result;
  }
  if (!isWindows) {
    return { ok: false, error: `autostart is not implemented for ${process.platform}; run server.mjs under your own supervisor` };
  }

  if (enabled) {
    const pythonw = pythonwPath();
    if (!pythonw) {
      return { ok: false, error: 'pythonw.exe not found; install Python or set PYTHONW_PATH, then retry' };
    }
    try {
      writeLauncher(pythonw);
    } catch (err) {
      return { ok: false, error: err.message };
    }
    const data = `"${pythonw}" "${LAUNCHER}"`;
    const r = run('reg.exe', ['add', RUN_KEY, '/v', VALUE_NAME, '/t', 'REG_SZ', '/d', data, '/f']);
    if (r.status !== 0) {
      return { ok: false, error: (r.stderr || r.stdout || 'reg add failed').trim() };
    }
    removeLegacyLauncher();
    installedCache = { value: true, at: Date.now() };
    return { ok: true, enabled: true, command: data, pythonw };
  }

  const r = run('reg.exe', ['delete', RUN_KEY, '/v', VALUE_NAME, '/f']);
  const missing = /unable to find|not found|找不到/i.test(`${r.stdout}${r.stderr}`);
  installedCache = { value: false, at: Date.now() };
  return { ok: r.status === 0 || missing, enabled: false };
}

export function autostartCommand() {
  if (isLinux) return `systemctl --user status ${UNIT_NAME}`;
  if (isMac) return '(unsupported)';
  const pythonw = pythonwPath();
  return pythonw ? `"${pythonw}" "${LAUNCHER}"` : '(pythonw.exe not found)';
}

export function platformInfo() {
  return {
    platform: process.platform,
    autostart: isWindows ? 'registry-run' : isLinux ? 'systemd-user' : 'none',
    unit: isLinux ? UNIT_PATH : null,
    node: process.execPath,
  };
}
